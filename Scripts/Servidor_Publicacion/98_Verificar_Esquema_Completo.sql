SELECT DISTINCT m.Tabla AS TablaFaltante
FROM @Modelo m
WHERE OBJECT_ID(N'dbo.' + m.Tabla, N'U') IS NULL
ORDER BY m.Tabla;

-- 2) Columnas que faltan en tablas existentes
SELECT m.Tabla, m.Columna AS ColumnaFaltante
FROM @Modelo m
WHERE OBJECT_ID(N'dbo.' + m.Tabla, N'U') IS NOT NULL
  AND COL_LENGTH(N'dbo.' + m.Tabla, m.Columna) IS NULL
ORDER BY m.Tabla, m.Columna;

-- 3) Resumen
SELECT
    (SELECT COUNT(DISTINCT Tabla) FROM @Modelo) AS TablasEsperadas,
    (SELECT COUNT(DISTINCT Tabla) FROM @Modelo WHERE OBJECT_ID(N'dbo.' + Tabla, N'U') IS NULL) AS TablasFaltantes,
    (SELECT COUNT(*) FROM @Modelo WHERE OBJECT_ID(N'dbo.' + Tabla, N'U') IS NOT NULL AND COL_LENGTH(N'dbo.' + Tabla, Columna) IS NULL) AS ColumnasFaltantes;
GO
